"""Audit local rollout-preference data before merging or training.

The audit is deliberately strict: it accepts only schema v2 data generated by
the reseeded counterfactual protocol and rejects old artifacts rather than
silently mixing them into a training run.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from collect_rollout_preferences import RNG_PROTOCOL, SCHEMA_VERSION


REQUIRED = {"features", "cards", "action_mask", "turns", "teacher_actions", "candidate_actions",
            "candidate_placements", "candidate_mean_placements", "best_actions", "metadata"}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    args = parser.parse_args()
    data = np.load(args.input)
    missing = REQUIRED - set(data.files)
    if missing:
        raise ValueError(f"missing required arrays: {sorted(missing)}")
    metadata = json.loads(str(data["metadata"]))
    if metadata.get("schema_version") != SCHEMA_VERSION:
        raise ValueError("unaudited schema: recollect with the current collector")
    if metadata.get("rng_protocol") != RNG_PROTOCOL:
        raise ValueError("unaudited RNG protocol: recollect with the current collector")
    if metadata.get("visible_observation_only") is not True:
        raise ValueError("dataset does not attest visible-observation-only features")
    actions = data["candidate_actions"]
    placements = data["candidate_placements"]
    if actions.ndim != 2 or placements.ndim != 3 or placements.shape[:2] != actions.shape:
        raise ValueError("candidate action/placement shapes are inconsistent")
    if np.any((actions < -1) | (actions >= 245)):
        raise ValueError("dataset contains an invalid action id")
    if np.any((placements < 0) | (placements > 8)):
        raise ValueError("dataset contains an invalid placement")
    print(json.dumps({"input": str(args.input), "states": int(actions.shape[0]),
                      "source_hash": metadata.get("source_hash"), "schema_version": SCHEMA_VERSION,
                      "rng_protocol": RNG_PROTOCOL, "audit": "PASS"}, ensure_ascii=False))


if __name__ == "__main__":
    main()
